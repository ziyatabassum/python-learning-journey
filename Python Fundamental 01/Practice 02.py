#Take two numbers as input from the user and print their sum, difference, product, and quotient

num1 = int(input("Type your 1st num: "))
num2 = int(input("Type your 2nd num: "))

sum = num1 + num2
difference = num1 - num2
product = num1 * num2
quotient = num1 / num2

print(f"The sum of {num1} + {num2} is = {sum}")
print(f"The difference of {num1} - {num2} is = {difference}")
print(f"The product of {num1} * {num2} is = {product}")
print(f"The quotient of {num1} / {num2} is = {quotient}")