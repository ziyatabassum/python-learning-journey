# Topic: print() function
# Use: This function helps us to display something (in any format) on the screen (the console)💻.
# Anything quotes(’’) or double-quotes(””) is called a string & gets printed as it is.

print("Hello Wizards!")                                          # output: Hello Wizards!
print('Welcome to Slytherin 🐍!')                               # output: Welcome to Slytherin 🐍!

# new line
print()                                                         # This will print an empty line. This is a new line after an empty line.

# \n is used to create a new line in the output.
print("Hello Wizards!\nWelcome to Slytherin🐍!")                # output: Hello Wizards
                                                                # Welcome to Slytherin🐍!

# We can also print numerical values:
print(42)                                                       # output: 42
print(3.14)                                                     # output: 3.14
print(2 + 3)                                                    # output: 5

# Each print statement displays output on different lines but we can also display multiple values on same line:
print("The answer is:", 42)                                     # output: The answer is: 42
print("The answer is:", 42, "and the value of pi is:", 3.14)    # output: The answer is: 42 and the value of pi is: 3.14

